#!/usr/bin/env node
/**
 * Preview image utility.
 *
 * Two jobs:
 *   1. Verify the preview manifest — every project in src/data/projects.ts has
 *      a screenshot in public/previews/ and a placeholder in
 *      src/data/previewPlaceholders.ts.
 *   2. Re-encode the tiny blurred placeholders from the full-size screenshots
 *      (requires `sharp`; see below).
 *
 * Runs with zero dependencies. The validation half is what matters when a
 * project is added by hand, and it needs nothing installed:
 *
 *     npm run previews
 *
 * To also regenerate the placeholders after replacing a screenshot:
 *
 *     npm i -D sharp
 *     npm run previews
 *
 * Placeholders are ~500 bytes each and are inlined as data URLs so a project
 * card paints something meaningful before its <img> finishes loading.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const projectsFile = join(root, 'src', 'data', 'projects.ts');
const placeholdersFile = join(root, 'src', 'data', 'previewPlaceholders.ts');
const previewsDir = join(root, 'public', 'previews');

/** Screenshot width in the placeholder data URL. Height follows the 16:10 crop. */
const PLACEHOLDER_WIDTH = 20;

const read = (file) => readFileSync(file, 'utf8');

/** Pulls every `slug: '...'` out of the project manifest. */
function readProjectSlugs() {
  const source = read(projectsFile);
  return [...source.matchAll(/slug:\s*'([^']+)'/g)].map((match) => match[1]);
}

/** Pulls every top-level key out of the placeholder map. */
function readPlaceholderSlugs() {
  return [...read(placeholdersFile).matchAll(/^\s{2}'([^']+)':/gm)].map((match) => match[1]);
}

function readPreviewFiles() {
  if (!existsSync(previewsDir)) return [];
  return readdirSync(previewsDir)
    .filter((file) => /\.(jpe?g|png|webp)$/i.test(file))
    .map((file) => file.replace(/\.[^.]+$/, ''));
}

/** Optional dependency — only needed to re-encode placeholders. */
async function loadSharp() {
  try {
    const { default: sharp } = await import('sharp');
    return sharp;
  } catch {
    return null;
  }
}

async function writePlaceholders(slugs, sharp) {
  const entries = [];

  for (const slug of slugs) {
    const candidates = ['jpg', 'jpeg', 'png', 'webp']
      .map((extension) => join(previewsDir, `${slug}.${extension}`))
      .filter((file) => existsSync(file));

    const source = candidates[0];
    if (!source) {
      console.warn(`  ! skipped ${slug}: no screenshot found`);
      continue;
    }

    const buffer = await sharp(source)
      .resize({ width: PLACEHOLDER_WIDTH })
      .jpeg({ quality: 30 })
      .toBuffer();

    entries.push(
      `  '${slug}': 'data:image/jpeg;base64,${buffer.toString('base64')}',`,
    );
  }

  const contents = `/**
 * Tiny blurred copies of each project screenshot (~500 bytes each) used as
 * the CSS background behind the lazily-loaded <img>, so cards paint
 * something meaningful instead of an empty box while the photo loads.
 *
 * Generated by \`npm run previews\` — do not edit by hand.
 */
export const previewPlaceholders: Record<string, string> = {
${entries.join('\n')}
};

export function placeholderFor(slug: string): string | undefined {
  return previewPlaceholders[slug];
}
`;

  writeFileSync(placeholdersFile, contents, 'utf8');
  return entries.length;
}

async function main() {
  const slugs = readProjectSlugs();
  const placeholders = readPlaceholderSlugs();
  const files = readPreviewFiles();

  if (slugs.length === 0) {
    console.error('No project slugs found in src/data/projects.ts.');
    process.exitCode = 1;
    return;
  }

  console.log(`Projects: ${slugs.length}\n`);

  const missingFiles = slugs.filter((slug) => !files.includes(slug));
  const missingPlaceholders = slugs.filter((slug) => !placeholders.includes(slug));
  const orphanFiles = files.filter((slug) => !slugs.includes(slug));
  const orphanPlaceholders = placeholders.filter((slug) => !slugs.includes(slug));

  for (const [label, items] of [
    ['Missing screenshot', missingFiles],
    ['Missing placeholder', missingPlaceholders],
    ['Unused screenshot', orphanFiles],
    ['Unused placeholder', orphanPlaceholders],
  ]) {
    if (items.length > 0) {
      console.log(`${label}:`);
      for (const item of items) console.log(`  - ${item}`);
      console.log('');
    }
  }

  const sharp = await loadSharp();

  if (sharp) {
    const written = await writePlaceholders(slugs, sharp);
    console.log(`Regenerated ${written} placeholder(s) at ${PLACEHOLDER_WIDTH}px wide.`);
  } else {
    console.log('Placeholders not regenerated (optional `sharp` is not installed).');
    console.log('Run `npm i -D sharp` then `npm run previews` to rebuild them.');
  }

  if (missingFiles.length > 0 || missingPlaceholders.length > 0) {
    console.error('\nPreview manifest is incomplete — fix the items above.');
    process.exitCode = 1;
    return;
  }

  console.log('\nPreview manifest is complete.');
}

await main();
